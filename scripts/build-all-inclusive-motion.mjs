// Build-time conversion of the verified Figma poses; no JS animation at runtime.
// Run: node scripts/build-all-inclusive-motion.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { sampleCards, sampleMobileCards } from '../october/themes/kv-vopros/assets/repairs/js/sections/all-inclusive-motion.js';

const output = new URL('../october/themes/kv-vopros/assets/repairs/css/sections/all-inclusive-motion.css', import.meta.url);
const number = value => Number(value.toFixed(7));
const transform = ([x, y, rotation]) => `translate(${number(x / 16)}rem, ${number(y / 16)}rem) rotate(${number(rotation)}deg)`;
const lines = ['/* Generated by scripts/build-all-inclusive-motion.mjs. Do not edit by hand. */'];
for (const [mode, sample] of [['desktop', sampleCards], ['mobile', sampleMobileCards]]) {
    for (let card = 0; card < 5; card++) {
        for (const property of ['transform', 'opacity']) {
            lines.push(`@keyframes all-inclusive-${mode}-${card}-${property} {`);
            for (let frame = 0; frame < 5; frame++) {
                const pose = sample(frame / 4)[card];
                lines.push(`    ${frame * 25}% { ${property}: ${property === 'transform' ? transform(pose) : pose[3]}; }`);
            }
            lines.push('}', '');
        }
    }
}
lines.push('@supports (animation-timeline: --all-inclusive) and (view-timeline-inset: 1px) and (animation-range: contain) {');
for (const [mode, width] of [['desktop', 'min-width: 1201px'], ['mobile', 'max-width: 1200px']]) {
    lines.push(`    @media (${width}) and (prefers-reduced-motion: no-preference) {`);
    for (let card = 0; card < 5; card++) {
        lines.push(`        .all-inclusive__card:nth-child(${card + 1}) {`,
            `            animation-name: all-inclusive-${mode}-${card}-transform, all-inclusive-${mode}-${card}-opacity;`, '        }');
    }
    lines.push('    }');
}
lines.push('}', '');
const css = lines.join('\n');
if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== css) throw new Error('Motion CSS needs regeneration');
    console.log('PASS: generated CSS matches the Figma motion data');
} else {
    writeFileSync(output, css);
}
